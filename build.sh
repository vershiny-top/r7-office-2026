#!/usr/bin/env bash
# Concatenate individual macros into run_all.js
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$DIR/src/macros/run_all.js"

{
    echo "// Auto-generated by build.sh — do not edit by hand."
    echo "// Concatenation of 00_setup_sheets.js .. 05_build_report.js."
    echo ""
    for f in "$DIR"/src/macros/0*.js; do
        echo "// ===== $(basename "$f") ====="
        cat "$f"
        echo ""
    done
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT") lines)"
