// R7-Office macro: ensure all target sheets exist, seed Справочники.
// Idempotent: safe to run twice.
(function () {
    var NEEDED = [
        'Товары_исходные', 'Товары_очищенные',
        'Поставщики_исходные', 'Поставщики_очищенные',
        'Продажи_исходные', 'Продажи_очищенные',
        'Клиенты_исходные', 'Клиенты_очищенные',
        'Справочники', 'Итоговый_отчет', 'Инструкция'
    ];

    function getOrCreate(name) {
        var sheets = Api.GetAllSheets();
        for (var i = 0; i < sheets.length; i++) {
            if (sheets[i].GetName() === name) return sheets[i];
        }
        return Api.AddSheet(name);
    }

    for (var i = 0; i < NEEDED.length; i++) getOrCreate(NEEDED[i]);

    var ref = getOrCreate('Справочники');

    // Categories  A:B
    ref.GetRange('A1:B1').SetValue([['Исходная', 'Канон']]);
    ref.GetRange('A2:B12').SetValue([
        ['Смартфоны', 'Смартфоны'],
        ['Телефоны', 'Смартфоны'],
        ['Мобильные телефоны', 'Смартфоны'],
        ['Ноутбуки', 'Ноутбуки'],
        ['Лэптопы', 'Ноутбуки'],
        ['Планшеты', 'Планшеты'],
        ['Телевизоры', 'Телевизоры'],
        ['Наушники', 'Наушники'],
        ['Мониторы', 'Мониторы'],
        ['Аксессуары', 'Аксессуары'],
        ['Часы', 'Часы']
    ]);

    // Units  D:E
    ref.GetRange('D1:E1').SetValue([['Исходная', 'Канон']]);
    ref.GetRange('D2:E5').SetValue([
        ['шт', 'шт.'], ['штука', 'шт.'], ['шт.', 'шт.'], ['штуки', 'шт.']
    ]);

    // Statuses  G:H
    ref.GetRange('G1:H1').SetValue([['Исходная', 'Канон']]);
    ref.GetRange('G2:H10').SetValue([
        ['Завершен', 'Завершен'], ['завершен', 'Завершен'],
        ['completed', 'Завершен'], ['выполнен', 'Завершен'],
        ['отменен', 'Отменен'], ['Отменен', 'Отменен'],
        ['canceled', 'Отменен'],
        ['возврат', 'Возврат'], ['Возврат', 'Возврат']
    ]);

    // Cities  J:K
    ref.GetRange('J1:K1').SetValue([['Исходная', 'Канон']]);
    ref.GetRange('J2:K8').SetValue([
        ['Москва', 'Москва'], ['г.Москва', 'Москва'],
        ['МСК', 'Москва'], ['г Москва', 'Москва'],
        ['Санкт-Петербург', 'Санкт-Петербург'],
        ['СПб', 'Санкт-Петербург'],
        ['СПБ', 'Санкт-Петербург']
    ]);

    // Currencies  M:N  (rate to RUB)
    ref.GetRange('M1:N1').SetValue([['Символ', 'Курс']]);
    ref.GetRange('M2:N4').SetValue([['$', 95], ['€', 100], ['₽', 1]]);
})();
